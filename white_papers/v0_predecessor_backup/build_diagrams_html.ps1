# build_diagrams_html.ps1
# Extracts every ```mermaid block from the HLD/LLD markdown files in this folder,
# HTML-escapes the source, and emits a single self-contained diagrams_rendered.html
# that renders all diagrams with the locally vendored mermaid.min.js (no network).

$ErrorActionPreference = 'Stop'
$dir  = Split-Path -Parent $MyInvocation.MyCommand.Path
$files = @('HLD_LLD_4x4_architecture.md', 'HLD_LLD_2x2_FPGA.md', 'HLD_LLD_2x2_presentation.md')

$cards = New-Object System.Collections.Generic.List[string]
$docTitle = 'HLD / LLD Diagrams - FINAL_whitepaper_v3.0'
$docSeen = $false

foreach ($f in $files) {
    $path = Join-Path $dir $f
    if (-not (Test-Path $path)) { Write-Warning "missing $f"; continue }
    $lines   = Get-Content -LiteralPath $path -Encoding UTF8
    $inBlock = $false
    $buf     = New-Object System.Collections.Generic.List[string]
    $heading = ''
    foreach ($line in $lines) {
        if (-not $inBlock -and $line -match '^#{1,6}\s+(.*)$') {
            $h = $Matches[1].Trim()
            if (-not $docSeen) { $docTitle = $h; $docSeen = $true }   # first H1 = document title
            $heading = $h
            continue
        }
        if ($line -match '^```mermaid\s*$') { $inBlock = $true; $buf.Clear(); continue }
        if ($inBlock -and $line -match '^```\s*$') {
            $inBlock = $false
            $src  = [System.Net.WebUtility]::HtmlEncode(($buf -join "`n"))
            $file = [System.Net.WebUtility]::HtmlEncode($f)
            $head = [System.Net.WebUtility]::HtmlEncode($heading)
            $n    = $cards.Count + 1
            $cards.Add(@"
  <div class="card">
    <div class="cardhead"><span class="num">$n</span><h3>$head</h3><span class="file">$file</span></div>
    <pre class="mermaid">$src</pre>
  </div>
"@)
            continue
        }
        if ($inBlock) { $buf.Add($line) }
    }
    if ($inBlock) { Write-Warning "unterminated mermaid block in $f" }
}

$html = @"
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>$([System.Net.WebUtility]::HtmlEncode($docTitle))</title>
<style>
  :root { color-scheme: light; }
  body { font-family: 'Segoe UI', system-ui, sans-serif; margin: 0; background: #f4f5f7; color: #1c2733; }
  header { background: #16324f; color: #fff; padding: 18px 28px; }
  header h1 { margin: 0; font-size: 22px; font-weight: 600; }
  header p { margin: 6px 0 0; font-size: 13px; opacity: .85; }
  main { padding: 20px 28px 60px; max-width: 1500px; margin: 0 auto; }
  .card { background: #fff; border: 1px solid #d8dee6; border-radius: 8px; margin: 0 0 24px; padding: 14px 18px 6px; box-shadow: 0 1px 2px rgba(0,0,0,.05); }
  .cardhead { display: flex; align-items: baseline; gap: 12px; border-bottom: 1px solid #e8ecf1; padding-bottom: 8px; margin-bottom: 10px; }
  .cardhead h3 { margin: 0; font-size: 16px; flex: 1; }
  .num { background: #16324f; color: #fff; border-radius: 4px; padding: 2px 8px; font-size: 12px; }
  .file { font-size: 11px; color: #6b7785; font-family: Consolas, monospace; }
  pre.mermaid { margin: 0 0 14px; text-align: center; background: transparent; }
  footer { text-align: center; font-size: 12px; color: #6b7785; padding: 0 0 30px; }
</style>
</head>
<body>
<header>
  <h1>$([System.Net.WebUtility]::HtmlEncode($docTitle))</h1>
  <p>Derived exclusively from FINAL_whitepaper_v3.0.md. &#9888; marks content not specified in the white paper and is deliberately not invented.</p>
</header>
<main>
$($cards -join "`n")
</main>
<footer>Generated by build_diagrams_html.ps1 &mdash; render offline via vendored mermaid.min.js</footer>
</body>
<script src="mermaid.min.js"></script>
<script>
  mermaid.initialize({ startOnLoad: true, securityLevel: 'loose', theme: 'neutral',
    flowchart: { htmlLabels: true, curve: 'basis' }, themeVariables: { fontSize: '13px' } });
</script>
</html>
"@

$out = Join-Path $dir 'diagrams_rendered.html'
[System.IO.File]::WriteAllText($out, $html, [System.Text.UTF8Encoding]::new($false))
Write-Host "wrote $out with $($cards.Count) diagrams"
